import assert from 'node:assert/strict';
import {dashboardFilterCandidates,makeDashboardInteractiveHtml} from '../src/dashboard-interactive.js';
import {chartCanSelect,markCategory,matchingRows,validSelection} from '../src/dashboard-links.js';
const make=(n)=>Array.from({length:n},(_,i)=>({Country:`Country ${i+1}`,Count:i+2}));
const many=make(195),cards=[{chart:{id:'a',type:'bar',x:'Country',y:'Count',title:'A'},rows:many},{chart:{id:'b',type:'hbar',x:'Country',y:'Count',title:'B'},rows:many}];
const choices=dashboardFilterCandidates(cards);
assert.equal(choices.find(c=>c.field==='Country').values.length,195,'large country list must be browsable');
assert(chartCanSelect(cards[0].chart,'Country'));
assert(!chartCanSelect({...cards[0].chart,x:'Count'},'Country'),'no inferred mismatch between category and value fields');
assert.equal(markCategory(cards[0].chart,'Country','Country 20',many),'Country 20');
assert.deepEqual(validSelection(['Country 20','Country 20','Country 1'],many.map(r=>r.Country)),['Country 20','Country 1']);
assert.equal(matchingRows(many,'Country',['Country 20','Country 1']).length,2);
const lite={name:'Countries',mode:'grid',chartIds:['a','b'],sharedFilterField:'Country',interactionMode:'filter'};
const html=makeDashboardInteractiveHtml(lite,cards,'Country');
assert(html.includes('exported version uses highlighting rather than recalculating'),'large exported dashboard must disclose filtered-mode limit');
assert(html.includes('data-cross-value="Country 195"'));
assert(!html.includes('id="db-0-f194"'),'must not render 195 variants per chart');
const malformed=makeDashboardInteractiveHtml({...lite,interactionMode:'</script><script>alert(1)</script>'},cards,'Country');
assert(!malformed.includes('alert(1)'),'invalid imported modes must not inject script');
console.log('PASS: 195-category linked selection catalogue, no inferred joins, bounded export, validation, source-row safety');
